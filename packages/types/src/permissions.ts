export type PermissionCode = (typeof PERMISSIONS)[number]['code'];

export const PERMISSION_CODES: readonly PermissionCode[] = PERMISSIONS.map(
  (permission) => permission.code,
);

/** Módulos que têm permissão no catálogo, na ordem de permissions.md §2. */
export const PERMISSION_MODULES: readonly string[] = [
  ...new Set(PERMISSIONS.map((permission) => permission.module)),
];

const PERMISSION_CODE_SET: ReadonlySet<string> = new Set(PERMISSION_CODES);

export function isPermissionCode(value: string): value is PermissionCode {
  return PERMISSION_CODE_SET.has(value);
}
