/**
 * Catálogo global de permissões do MVP 1 (permissions.md §2 · DEC-134 · US-094 · RN-IAM-73),
 * fonte única para api e web. Códigos `RESOURCE_ACTION` estáveis (DEC-001). A tabela `permissions`
 * é sincronizada a partir desta lista por migração (upsert por `code`); permissão nova do roadmap
 * passa pela mesma esteira: entrada aqui → migração → matriz de perfis padrão (`access`).
 * Nunca remova uma entrada: descontinue com `isDeprecated: true`.
 */

